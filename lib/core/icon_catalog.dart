/// بحث سريع بالمفتاح في كل الأقسام.
(IconEntry, IconSection)? catalogEntry(String key) {
  _idx ??= {
    for (final s in kIconSections)
      for (final e in s.items) e.key: (e, s),
  };
  return _idx![key];
}

IconData? catalogIcon(String key) => catalogEntry(key)?.$1.icon;
