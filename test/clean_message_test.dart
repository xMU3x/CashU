import 'package:flutter_test/flutter_test.dart';
import 'package:cashu/sms/sms_text.dart';

void main() {
  test('تحويل لحظي: حذف الافتتاحية والختام واختصار الحساب مع بقاء المبلغ والتاريخ والمرجع', () {
    expect(
      cleanBankMessage('يرجى العلم أنه تم تنفيذ تحويل لحظي بمبلغ 325.00 جم إلى حسابك ****7748 من احمد عادل عبدالمنصف شري برقم مرجعي 86afa5ec بتاريخ 23-10-2026 12:42 للمزيد، برجاء الاتصال بـ 19666'),
      'تم تنفيذ تحويل لحظي بمبلغ 325.00 جم إلى حسابك **7748 من احمد عادل عبدالمنصف شري برقم مرجعي 86afa5ec بتاريخ 23-10-2026 12:42',
    );
  });
  test('كارت مقنّع + أرقام عربية', () {
    expect(
      cleanBankMessage('عزيزي العميل، تم خصم ١٬٢٥٠٫٥٠ جم من بطاقتك XXXXXXXXXXXX1234 لدى Carrefour بتاريخ 2026-10-01 14:05'),
      'تم خصم 1,250.50 جم من بطاقتك **1234 لدى Carrefour بتاريخ 2026-10-01 14:05',
    );
  });
  test('رقم حساب طويل بلا أقنعة يُختصر لآخر 4', () {
    expect(cleanBankMessage('تم إيداع 500.00 جم في حسابك 1234567890123 شكرا لاستخدامك بنكنا'), 'تم إيداع 500.00 جم في حسابك **0123');
  });
  test('نص بلا ضوضاء يبقى كما هو', () {
    expect(cleanBankMessage('رسالة بسيطة 100 جم'), 'رسالة بسيطة 100 جم');
  });
}
