import re,sys
AR='٠١٢٣٤٥٦٧٨٩'
def ascii_digits(s):
    return ''.join(str(AR.index(c)) if c in AR else ('.' if c=='٫' else (',' if c=='٬' else c)) for c in s)
LEAD=[r'^\s*(?:عزيزي|عزيزتي|عميلنا|عميلتنا)\s+(?:العميل|العميلة|العزيز|العزيزة)?\s*[،,:\-]?\s*',
 r'^\s*يرجى\s+العلم\s+(?:بأنه|بان|أنه|انه|أن|ان)\s*',
 r'^\s*نود\s+(?:إعلامك|اعلامك|إبلاغك|ابلاغك)\s+(?:بأنه|بان|أنه|انه|أن|ان)\s*',
 r'^\s*(?:تنبيه|إشعار|اشعار)\s*[:：\-]\s*']
TAIL=[r'[\s،,.\-–]*(?:للمزيد|للاستفسار|للاستعلام|لمزيد\s+من\s+المعلومات)[^\n]{0,40}?(?:اتصل|الاتصال|اتصال|تواصل|التواصل|call)[^\n]*$',
 r'[\s،,.\-–]*(?:برجاء|يرجى|من\s+فضلك)\s+(?:الاتصال|الإتصال|التواصل)\s+(?:ب|على|علي)?[^\n]*$',
 r'[\s،,.\-–]*(?:للإبلاغ|للابلاغ)\s+عن\s+(?:أي|اي)\s+(?:معاملة|عملية)[^\n]*$',
 r'[\s،,.\-–]*(?:شكرا|شكراً)\s+(?:لاستخدامك|لتعاملك|لثقتك)[^\n]*$']
MASK=re.compile(r'(?:[*xX•●#]{2,}[\s\-]*)+(\d{3,})(?!\d)')
LONG=re.compile(r'(?<![\d.,:/\-])\d{9,}(?![\d.,:/\-])')
def clean(raw):
    o=raw.strip()
    if not o: return o
    s=re.sub(r'\s+',' ',ascii_digits(o)).strip()
    for _ in range(3):
        b=s
        for r in LEAD: s=re.sub(r,'',s,count=1)
        if s==b: break
    for r in TAIL: s=re.sub(r,'',s,count=1,flags=re.I)
    s=MASK.sub(lambda m:'**'+(m[1][-4:] if len(m[1])>4 else m[1]),s)
    s=LONG.sub(lambda m:'**'+m[0][-4:],s)
    s=re.sub(r'\s+',' ',s).strip()
    s=re.sub(r'[\s،,.\-–:]+$','',s)
    if not s: return o
    for m in re.finditer(r'\d+(?:[.,:\-/]\d+)*',ascii_digits(o)):
        t=m[0]
        if len(t)<9 and t!='19666' and t not in s: return o
    return s
